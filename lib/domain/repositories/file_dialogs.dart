import 'dart:typed_data';

/// Системные диалоги выбора файла.
///
/// На Android доступ к произвольным местам хранения без разрешений дает только
/// системный SAF, поэтому сохранение выгрузки и резервной копии и выбор файла при
/// восстановлении выполняются через него (ADR-0006, решение 6.5). Интерфейс
/// скрывает платформенный плагин: доменные сценарии и тесты работают с ним.
abstract interface class FileDialog {
  /// Сохраняет [bytes] в место, выбранное пользователем.
  ///
  /// Возвращает адрес сохраненного файла или `null`, если пользователь отменил
  /// диалог: в этом случае файл не создается.
  Future<Uri?> saveBytes({
    required String fileName,
    required Uint8List bytes,
    required String mimeType,
    String? dialogTitle,
  });

  /// Читает байты файла, выбранного пользователем.
  ///
  /// Возвращает `null`, если пользователь отменил диалог.
  Future<Uint8List?> pickBytes({String? dialogTitle});
}
