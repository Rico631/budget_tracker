import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Путь активной базы данных, определенный до запуска приложения.
///
/// `null` означает дефолтный путь платформы: база открывается по имени
/// `budget_tracker`. Корень приложения переопределяет провайдер абсолютным
/// путем активной базы из реестра, поэтому после переключения базы или
/// восстановления приложение открывает выбранный файл (ADR-0006, решение 6.7).
final activeDatabasePathProvider = Provider<String?>((ref) => null);

/// Команда мягкого перезапуска приложения.
typedef AppRestart = void Function();

/// Команда мягкого перезапуска, доступная из UI.
///
/// Корень приложения переопределяет провайдер: команда освобождает контейнер
/// провайдеров, закрывая соединение с текущей базой, и создает новый контейнер
/// с базой по новому активному пути (ADR-0006, решение 6.6). Обращение к
/// провайдеру без переопределения означает, что корень приложения не установлен
/// и перезапускать нечего.
final appRestartProvider = Provider<AppRestart>(
  (ref) => throw StateError(
    'appRestartProvider не переопределен: мягкий перезапуск выполняет корень '
    'приложения.',
  ),
);
